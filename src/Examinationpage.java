public void answerCheck(){
String studentAnswer = "";

    if (jRadioButton1.isSelected()) {
        studentAnswer = jRadioButton1.getText();
    } else if (jRadioButton2.isSelected()) {
        studentAnswer = jRadioButton2.getText();
    } else if (jRadioButton3.isSelected()) {
        studentAnswer = jRadioButton3.getText();
    } else if (jRadioButton4.isSelected()) {
        studentAnswer = jRadioButton4.getText();
    }

    if (studentAnswer.equals(answer)) {
        marks++;
    }
}


public void question(){
    try {
        java.sql.Connection con = ConnectionProvider.getCon();
        Statement st = con.createStatement();

        

        ResultSet rsl = st.executeQuery(
            "select * from question where id='" + questionId + "'"
        );

        while (rsl.next()) {
            jLabel13.setText(rsl.getString(1));
            jLabel11.setText(rsl.getString(7));
            jRadioButton1.setText(rsl.getString(2));
            jRadioButton2.setText(rsl.getString(3));
            jRadioButton3.setText(rsl.getString(4));
            jRadioButton4.setText(rsl.getString(5));
            answer = rsl.getString(6);
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e);
    }
}
