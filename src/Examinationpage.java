    public Examinationpage(String rollNo) {
        initComponents();
        setupButtonGroup(); 


    jLabel10.setText(rollNo);

    SimpleDateFormat dFormat = new SimpleDateFormat("dd-MM-yyyy");
    Date date = new Date();
    jLabel5.setText(dFormat.format(date));

    // first question and student details
    try {
        Connection con = ConnectionProvider.getCon();
        Statement st = con.createStatement();

        ResultSet rs = st.executeQuery(
            "select * from student where rollNo='" + rollNo + "'"
        );

        while (rs.next()) {
            jLabel15.setText(rs.getString(2));
        }

        ResultSet rsl = st.executeQuery(
            "select * from question where id='" + questionId + "'"
        );

        while (rsl.next()) {
            jLabel13.setText(rsl.getString(1));
            jLabel11.setText(rsl.getString(7));
            jRadioButton1.setText(rsl.getString(2));
            jRadioButton2.setText(rsl.getString(3));
            jRadioButton3.setText(rsl.getString(4));
            jRadioButton4.setText(rsl.getString(5));
            answer = rsl.getString(6);
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e);
    }

    // time program
    setLocationRelativeTo(this);

        time = new Timer(1000, new ActionListener() {
    @Override
    public void actionPerformed(ActionEvent e) {
        jLabel18.setText(String.valueOf(sec));
        jLabel19.setText(String.valueOf(min));

        if (sec == 60) {
            sec = 0;
            min++;
        }

        if (min == 2) {
            time.stop();
            submit();
        }
        sec++;
    }
});
time.start();


    }

